import { registerHooks } from 'node:module';
import { existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import assert from 'node:assert/strict';
registerHooks({ resolve(specifier, context, next) { if (specifier.startsWith('.') && context.parentURL?.startsWith('file:')) { const base = new URL(specifier, context.parentURL); for (const ext of ['.ts', '.tsx']) { if (existsSync(fileURLToPath(base) + ext)) return next(base.href + ext, context); }} return next(specifier,context); }});
const {buildSections,nextUpcoming,allCaughtUp}=await import(new URL('../../../../src/screens/choreListModel.ts', import.meta.url).href);
const today='2026-10-07';
const base={homeId:'h',objectId:'sink',createdOn:today,photoProof:false};
const chores=[{...base,id:'dishes',name:'Wash the dishes',schedule:{kind:'daily'}},{...base,id:'scrub',name:'Scrub the sink',schedule:{kind:'weekly',weekday:1}}];
const done=[{id:'c',choreId:'dishes',completedOn:today,completedAt:today+'T12:00:00Z',counts:true}];
const sections=buildSections(chores,done,[],today);
assert.equal(allCaughtUp(sections),true);
assert.equal(sections.find(s=>s.id==='done').rows[0].status.dueDate,'2026-10-08');
assert.equal(nextUpcoming(sections).chore.id,'scrub');
assert.equal(nextUpcoming(sections).status.dueDate,'2026-10-12');
console.log(JSON.stringify({caughtUp:allCaughtUp(sections),sections:sections.map(s=>({id:s.id,rows:s.rows.map(r=>({name:r.chore.name,due:r.status.dueDate,label:r.label}))})),next:nextUpcoming(sections).chore.name},null,2));
const onlyDaily=buildSections(chores.slice(0,1),done,[],today);
assert.equal(nextUpcoming(onlyDaily),null);
console.log('With only the daily chore, nextUpcoming returns null despite tomorrow\'s scheduled occurrence.');
